import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import Ajv2020 from 'ajv2020/dist/2020.js';
import standaloneCode from 'ajv2020/dist/standalone/index.js';
import { _ } from 'ajv2020/dist/compile/codegen/index.js';
import { manuscriptFormats, reportFormats } from '../src/services/schemaFormats.ts';

// Compile only at build time: Ajv's Function constructor cannot run in the
// privileged Tauri WebView, whose script-src deliberately excludes unsafe-eval.
const directory = new URL('../src/services/generated/', import.meta.url);
const check = process.argv.includes('--check');
if (!check) mkdirSync(directory, { recursive: true });
function emit(file, content) {
  const path = new URL(file, directory);
  if (check) {
    if (readFileSync(path, 'utf8') !== content) throw new Error(`${file} is stale: run npm run schemas:generate`);
  } else {
    writeFileSync(path, content);
  }
}
for (const [name, schemaFile, formats] of [
  ['manuscript', 'omi-manuscript-0.3.schema.json', manuscriptFormats],
  ['report', 'studio-validation-report-0.1.schema.json', reportFormats],
]) {
  const schema = JSON.parse(readFileSync(new URL(`../src/schemas/${schemaFile}`, import.meta.url), 'utf8'));
  const ajv = new Ajv2020({
    allErrors: true, strict: true, validateFormats: true,
    code: { source: true, esm: true, lines: true, formats: _`formats` },
  });
  for (const [format, validate] of Object.entries(formats)) ajv.addFormat(format, validate);
  let code = standaloneCode(ajv, ajv.compile(schema));
  let imports = `import { ${name === 'manuscript' ? 'manuscriptFormats' : 'reportFormats'} as formats } from '../schemaFormats';\n`;
  // Ajv emits CommonJS references for its two pure runtime helpers even in ESM
  // mode. Import those helpers through our npm alias without shipping the compiler.
  for (const helper of ['ucs2length', 'equal']) {
    const reference = `require("ajv/dist/runtime/${helper}").default`;
    if (code.includes(reference)) {
      imports += `import ${helper}Module from 'ajv2020/dist/runtime/${helper}.js';\n`;
      imports += `const ${helper} = ${helper}Module.default ?? ${helper}Module;\n`;
      code = code.replaceAll(reference, helper);
    }
  }
  if (/\brequire\(/u.test(code)) throw new Error(`Unsupported standalone runtime dependency in ${name}`);
  emit(`${name}.js`, `// Generated by npm run schemas:generate. Do not edit.\n${imports}${code}`);
  const type = name === 'report' ? "import type { ValidationReport } from '../../model/validation';\n" : '';
  emit(`${name}.d.ts`, `// Generated by npm run schemas:generate. Do not edit.\nimport type { ValidateFunction } from 'ajv2020';\n${type}declare const validate: ValidateFunction<${name === 'report' ? 'ValidationReport' : 'unknown'}>;\nexport { validate };\nexport default validate;\n`);
}
