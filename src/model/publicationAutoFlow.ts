import {
  createFrameLayout, flowFrameStories, frameChain, frameStyle, MM_PER_POINT, RECTANGLE_POINTS,
  type FrameTextMeasure, type PublicationFrame, type PublicationFrameLayout,
} from './publicationFrames';
import {
  defaultFramePageStyle, deleteFramePage, framePageStyle, insertFramePage, withFramePages,
} from './publicationFramePages';

/** New manuscripts have one editable A4 text frame, inset 25 mm on all four sides. */
export function createDefaultFlowFrameLayout(): PublicationFrameLayout {
  const layout = withFramePages(createFrameLayout(210, 297));
  const style = defaultFramePageStyle(210, 297);
  style.margins = { top: 25, right: 25, bottom: 25, left: 25 };
  layout.pageStyles = [style];
  layout.pages = [{ id: 'frame-page-1', styleId: style.id }];
  layout.styles[0]!.properties = { ...layout.styles[0]!.properties, paddingMm: 0, strokeWidthMm: 0 };
  layout.autoFlowStoryId = 'omi-main-story';
  layout.stories = [{ id: layout.autoFlowStoryId, name: 'Main text', text: '' }];
  layout.frames = [{
    id: 'omi-main-frame-1', name: 'Main text frame', kind: 'text', page: 0,
    xMm: 25, yMm: 25, widthMm: 160, heightMm: 247,
    rotation: 0, shape: 'rectangle', points: structuredClone(RECTANGLE_POINTS),
    styleId: layout.styles[0]!.id, storyId: layout.autoFlowStoryId,
  }];
  return layout;
}

function uniqueId(prefix: string, ids: Set<string>): string {
  let value = prefix;
  for (let suffix = 2; ids.has(value); suffix += 1) value = `${prefix}-${suffix}`;
  return value;
}

/**
 * Generate and remove only explicitly automatic continuation pages.
 * Keep manually added pages, manually linked frames, graphics, styles and story text untouched.
 * The calculation is deterministic for an unchanged layout and text measurement function.
 */
export function paginateAutomaticFrameLayout(
  layout: PublicationFrameLayout,
  measure: FrameTextMeasure,
): PublicationFrameLayout {
  const storyId = layout.autoFlowStoryId;
  if (!storyId) return layout;
  const story = layout.stories.find((item) => item.id === storyId);
  if (!story) return layout;

  let next = withFramePages(layout);
  const root = () => next.frames.find((frame) =>
    frame.kind === 'text' && frame.storyId === storyId
      && !next.frames.some((item) => item.nextFrameId === frame.id));
  let first = root();
  if (!first) return next;

  let flow = flowFrameStories(next, measure);
  const overflow = () => flow.overflow.find((item) => item.storyId === storyId);

  // Remove only trailing untouched pages generated by this function when text shrinks.
  while (next.page.count > 1) {
    first = root();
    if (!first) break;
    const tail = frameChain(next, first.id).at(-1);
    const placement = tail && flow.frames.find((item) => item.frameId === tail.id);
    const page = tail && next.pages?.[tail.page];
    if (!tail?.autoGenerated || !page?.autoGenerated || tail.page !== next.page.count - 1
      || next.frames.some((frame) => frame.page === tail.page && frame.id !== tail.id)
      || !placement || placement.end !== placement.start) break;
    next = deleteFramePage(next, tail.page);
    flow = flowFrameStories(next, measure);
  }

  // A rough estimate reduces repeated full-text segmentation for long documents.
  // Always use the actual measured flow to determine the final page count.
  for (let round = 0; overflow() && next.page.count < 100 && round < 8; round += 1) {
    first = root();
    if (!first) break;
    const tail = frameChain(next, first.id).at(-1)!;
    const previousOffset = flow.frames.find((item) => item.frameId === tail.id)?.end ?? 0;
    const style = frameStyle(next, tail);
    const width = Math.max(0, tail.widthMm - 2 * style.paddingMm);
    const height = Math.max(0, tail.heightMm - 2 * style.paddingMm);
    const lineHeight = style.lineHeightPt * MM_PER_POINT;
    const averageGlyph = Math.max(0.01, measure('abcdefghijklmnopqrstuvwx', style) / 24);
    const capacity = Math.floor(height / lineHeight) * Math.floor(width / averageGlyph);
    if (capacity <= 0) break;
    const remaining = overflow()!.text.length;
    const batch = Math.min(100 - next.page.count, Math.max(1, Math.ceil(remaining / Math.max(1, capacity * 0.8))));
    const pageStyleId = framePageStyle(next, tail.page).id;
    let previous: PublicationFrame = tail;
    for (let i = 0; i < batch; i += 1) {
      const pageId = uniqueId(`omi-auto-page-${next.page.count + 1}`, new Set(next.pages!.map((page) => page.id)));
      next = insertFramePage(next, next.page.count - 1, pageStyleId, pageId);
      next.pages![next.page.count - 1]!.autoGenerated = true;
      const id = uniqueId(`omi-auto-frame-${next.page.count}`, new Set(next.frames.map((frame) => frame.id)));
      const continuation: PublicationFrame = {
        ...structuredClone(previous), id, name: `Continuation ${next.page.count}`,
        page: next.page.count - 1, autoGenerated: true, nextFrameId: undefined,
      };
      previous.nextFrameId = id;
      next.frames.push(continuation);
      previous = continuation;
    }
    flow = flowFrameStories(next, measure);
    // A frame too narrow for even one grapheme must report overflow, not create 100 empty pages.
    if ((flow.frames.find((item) => item.frameId === previous.id)?.end ?? 0) <= previousOffset) break;
  }

  // The estimate can overshoot; prune empty automatic pages at the end.
  while (next.page.count > 1) {
    first = root();
    if (!first) break;
    const tail = frameChain(next, first.id).at(-1);
    const placement = tail && flow.frames.find((item) => item.frameId === tail.id);
    if (!tail?.autoGenerated || !next.pages?.[tail.page]?.autoGenerated
      || tail.page !== next.page.count - 1 || !placement || placement.start !== placement.end
      || next.frames.some((frame) => frame.page === tail.page && frame.id !== tail.id)) break;
    next = deleteFramePage(next, tail.page);
    flow = flowFrameStories(next, measure);
  }
  return next;
}
