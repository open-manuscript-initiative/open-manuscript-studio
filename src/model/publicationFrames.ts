/** Keep layout anchors attached to surviving text after a single text edit. */
export function updateFrameStoryText(story: FrameStory, text: string): FrameStory {
  let start = 0;
  while (start < story.text.length && start < text.length && story.text[start] === text[start]) start += 1;
  let oldEnd = story.text.length, newEnd = text.length;
  while (oldEnd > start && newEnd > start && story.text[oldEnd - 1] === text[newEnd - 1]) { oldEnd -= 1; newEnd -= 1; }
  const shifted = story.breaks?.flatMap((point) => point.offset > start && point.offset < oldEnd ? []
    : [{ ...point, offset: point.offset >= oldEnd ? point.offset + newEnd - oldEnd : point.offset }]);
  const boundaries = shifted?.length ? new Set([text.length, ...Array.from(new Intl.Segmenter(undefined, { granularity: 'grapheme' }).segment(text), (part) => part.index)]) : undefined;
  const breaks = shifted ? [...new Map(shifted.filter((point) => boundaries?.has(point.offset)).map((point) => [point.offset, point])).values()] : undefined;
  return { ...story, text, ...(breaks ? { breaks } : {}) };
}
export interface PublicationFrameLayout {
  profile: typeof FRAME_LAYOUT_PROFILE;
  page: { widthMm: number; heightMm: number; count: number };
  styles: PublicationFrameStyle[]; stories: FrameStory[]; frames: PublicationFrame[];
  pageStyles?: FramePageStyle[]; pages?: FramePage[]; pageNumberStart?: number;
  /** Optional text story which automatically continues in new pages. */
  autoFlowStoryId?: string;
}
export interface FrameLine { text: string; start: number; end: number; x: number; y: number; width: number; hyphenated?: boolean; wordSpacingMm?: number }
export interface FrameTextFlowOptions { language?: string; hyphenate?: (word: string, language: string) => readonly number[] }
export interface FrameFlow { frameId: string; start: number; end: number; lines: FrameLine[] }
export interface PublicationFrameFlow { frames: FrameFlow[]; overflow: { storyId: string; offset: number; text: string }[] }
export function frameDisplayText(text: string): string { return text.replace(/\t/g, '    '); }
export function frameLineDisplayText(line: FrameLine): string {
  const text = frameDisplayText(line.text);
  return (line.wordSpacingMm ? text.trimEnd() : text) + (line.hyphenated ? '-' : '');
}
