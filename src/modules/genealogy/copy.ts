export type GraphCopy = typeof en;
export function graphCopy(locale: string): GraphCopy {
  return locale.toLowerCase().startsWith('hu')
    ? hu
    : locale.toLowerCase().startsWith('de')
      ? de
      : en;
}
export function nodeLabels(t: GraphCopy): Record<NodeKind, string> {
  return {
    person: t.person,
    organization: t.organization,
    place: t.place,
    event: t.event,
  };
}
export function relationLabels(t: GraphCopy): Record<RelationKind, string> {
  return {
    parent: t.parent,
    partner: t.partner,
    kinship: t.kinship,
    godparent: t.godparent,
    patronage: t.patronage,
    correspondence: t.correspondence,
    teacher: t.teacher,
    membership: t.membership,
    employment: t.employment,
    other: t.other,
  };
}
