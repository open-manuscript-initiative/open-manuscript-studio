/** The feedback module has reviewed translations for the eight primary languages. */
export function resolveStudioFeedbackLocale(locale: string): FeedbackUiLocale {
  const base = locale.toLowerCase().replace(/_/g, '-').split('-')[0];
  return base in copyByLanguage ? base as FeedbackUiLocale : 'en';
}
export function getStudioFeedbackCopy(locale: string): StudioFeedbackCopy {
  return copyByLanguage[resolveStudioFeedbackLocale(locale)];
}
