function rootStateWithDeletedBlock(current: OmiManuscriptState): OmiManuscriptState {
  const root = JSON.parse(JSON.stringify(current)) as OmiManuscriptState;
  root.updatedAt = REFERENCE_TIMESTAMP_ROOT;
  root.tombstones = [];
  const introduction = root.sections.find((section) => section.id === 'section-introduction');
  introduction?.blocks.push({
    id: 'block-deleted-reference',
    type: 'paragraph',
    content: documentNode(paragraph(text('This block exists only in the root revision and is deleted in the current state.'))),
  });
  return root;
}

