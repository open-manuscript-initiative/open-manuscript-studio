type JsonNode = Record<string, unknown>;

function documentNode(...content: JsonNode[]): string {
  return JSON.stringify({ type: 'doc', content });
}

function heading(level: number, text: string): JsonNode {
  return {
    type: 'heading',
    attrs: { level },
    content: [{ type: 'text', text }],
  };
}

function paragraph(...content: JsonNode[]): JsonNode {
  return { type: 'paragraph', content };
}

function text(value: string, marks?: JsonNode[]): JsonNode {
  return {
    type: 'text',
    text: value,
    ...(marks?.length ? { marks } : {}),
  };
}

function mark(type: string, attrs?: Record<string, unknown>): JsonNode {
  return { type, ...(attrs ? { attrs } : {}) };
}

