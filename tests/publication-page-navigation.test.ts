test('page styles use unambiguous letters beyond Z, independent of page order', () => {
  assert.deepEqual([0, 25, 26, 27, 51, 52, 701, 702].map(publicationPageStyleLetter), ['A', 'Z', 'AA', 'AB', 'AZ', 'BA', 'ZZ', 'AAA']);
  for (const index of [-1, NaN, 1.5, Infinity]) assert.throws(() => publicationPageStyleLetter(index));
});

test('moving a page preserves styles, frame geometry, links and source text through OMI save/reopen', () => {
  let layout = withFramePages(createFrameLayout());
  layout.pageStyles!.push({ ...defaultFramePageStyle(240, 150), id: 'wide', name: 'Wide' });
  layout = insertFramePage(layout, 0, 'wide', 'second');
  layout = insertFramePage(layout, 1, 'frame-page-style-default', 'third');
  layout.pages![1]!.autoGenerated = true;
  layout.stories = [{ id: 'story', name: 'Story', text: 'All original characters remain here.' }];
  layout.frames = [0, 1, 2].map((page) => ({ id: `f${page}`, name: `f${page}`, kind: 'text' as const, page,
    xMm: 19 + page, yMm: 20, widthMm: 65, heightMm: 80, rotation: 11,
    shape: 'rectangle' as const, points: structuredClone(RECTANGLE_POINTS), styleId: 'frame-style-default', storyId: 'story',
    ...(page < 2 ? { nextFrameId: `f${page + 1}` } : {}), ...(page === 1 ? { autoGenerated: true } : {}) }));
  const original = structuredClone(layout);
  const moved = moveFramePage(layout, 1, 0);
  assert.deepEqual(moved.pages!.map((page) => page.id), ['second', 'frame-page-1', 'third']);
  assert.deepEqual(moved.frames.map((frame) => frame.page), [1, 0, 2]);
  assert.equal(moved.pages![0]!.styleId, 'wide'); assert.equal(moved.pages![0]!.autoGenerated, false);
  assert.equal(moved.frames[1]!.autoGenerated, false);
  assert.deepEqual(moved.stories, original.stories);
  assert.deepEqual(moved.frames.map(({ page: _page, autoGenerated: _auto, ...frame }) => frame), original.frames.map(({ page: _page, autoGenerated: _auto, ...frame }) => frame));
  assert.deepEqual(layout, original); validateFrameLayout(moved);
  const manuscript = createVersionedTestManuscript(); manuscript.extensions = { [FRAME_LAYOUT_EXTENSION]: moved };
  assert.deepEqual(getFrameLayout(parseOmiJson(serializeOmiJson(manuscript))), moved);
  for (const [from, to] of [[-1, 0], [0, 3], [0.2, 1]]) assert.throws(() => moveFramePage(layout, from!, to!));
});

test('blank pages can be inserted before/after the last paragraph and reordered at a shared anchor', () => {
  const collection = { version: 1 as const, styles: [], sections: [], pages: [], insertions: [] };
  const before = placePublicationEmptyPage(collection, { id: 'before' }, thumbnail, 'before');
  const after = placePublicationEmptyPage(before, { id: 'after' }, thumbnail, 'after');
  assert.deepEqual(after.insertions, [{ id: 'before', styleId: undefined, beforeBlockId: 'first' }, { id: 'after', styleId: undefined, afterBlockId: 'last' }]);
  const adjacent = placePublicationEmptyPage(after, { id: 'between' }, { ...thumbnail, insertionId: 'after' }, 'before');
  assert.deepEqual(adjacent.insertions!.map((item) => item.id), ['before', 'between', 'after']);
  assert.equal(adjacent.insertions![1]!.afterBlockId, 'last');
  const moved = placePublicationEmptyPage(adjacent, adjacent.insertions![0]!, { ...thumbnail, insertionId: 'after' }, 'after');
  assert.deepEqual(moved.insertions!.map((item) => item.id), ['between', 'after', 'before']);
  validatePublicationPageStyles(moved);
  assert.throws(() => validatePublicationPageStyles({ ...moved, insertions: [{ id: 'bad', beforeBlockId: 'a', afterBlockId: 'b' }] }));
  assert.throws(() => validatePublicationPageStyles({ ...moved, insertions: [{ id: 'bad' }] }));
});

test('after-block pagination reserves one blank sheet each, carries notes first and creates no phantom final page', () => {
  const block = { top: 0, height: 20, sectionId: 's', insertedPagesAfter: [{ id: 'a' }, { id: 'b', styleId: 'plate' }] };
  let layout = paginatePublicationBlocks([block], 100, 20, undefined, metrics);
  assert.equal(layout.pageCount, 3); assert.deepEqual(layout.insertedPages!.map((item) => item.pageIndex), [1, 2]);
  layout = paginatePublicationBlocks([block, { top: 20, height: 20, sectionId: 's' }], 100, 20, undefined, metrics);
  assert.equal(layout.pageCount, 4); assert.equal(layout.placements[1]!.pageIndex, 3);
  const noted = paginatePublicationBlocks([{ ...block, noteIds: ['note'] }], 100, 20,
    { heights: new Map([['note', 120]]), lineHeight: 10, separatorHeight: 5 }, metrics);
  assert.ok(noted.insertedPages![0]!.pageIndex > 1);
  for (const inserted of noted.insertedPages!) assert.equal(noted.pageNotes?.[inserted.pageIndex]?.length ?? 0, 0);
});

test('after-block blank placement closes nested HTML elements and escapes identifiers', () => {
  const style = clonePublicationStyleTemplate();
  style.pageStyles = { version: 1, styles: [], sections: [], pages: [], insertions: [
    { id: 'before', beforeBlockId: 'table' }, { id: 'after', afterBlockId: 'table' }, { id: 'last', afterBlockId: 'end' },
    { id: 'unused', afterBlockId: 'removed' }, { id: '<SCRIPT>alert(1)</SCRIPT>', afterBlockId: 'end' },
  ] };
  const html = '<article><figure data-omi-block-id="table"><table><tbody><tr><td title="a > b"><figure><img src="x"></figure>Text</td></tr></tbody></table></figure><p data-omi-block-id="end">END</p></article>';
  const result = withInsertedPublicationPages(html, style);
  assert.match(result, /data-omi-inserted-page="before"[^]*?<figure data-omi-block-id="table"/);
  assert.match(result, /<\/table><\/figure><div[^]*?data-omi-inserted-page="after"/);
  assert.match(result, /END<\/p><div[^]*?data-omi-inserted-page="last"/);
  assert.doesNotMatch(result, /data-omi-inserted-page="unused"|<script\b/i);
  assert.match(result, /&lt;SCRIPT&gt;/);
});

test('thumbnail study moves preserve descendants, annotations and stable block identities atomically', () => {
  const original = useStudioStore.getState();
  try {
    const manuscript = createVersionedTestManuscript();
    manuscript.sections = [
      { id: 'a', title: 'A', blocks: [{ id: 'a-body', type: 'paragraph', content: 'A' }] },
      { id: 'child', title: 'Child', parentSectionId: 'a', blocks: [{ id: 'child-body', type: 'paragraph', content: 'Child' }] },
      { id: 'b', title: 'B', blocks: [{ id: 'b-body', type: 'paragraph', content: 'B' }] },
      { id: 'c', title: 'C', blocks: [] },
    ];
    useStudioStore.setState({ manuscript, pendingChangeSet: null });
    assert.equal(stageMoveSectionToSibling('a', 'c', true), true);
    assert.deepEqual(useStudioStore.getState().manuscript.sections.map((section) => section.id), ['b', 'c', 'a', 'child']);
    assert.deepEqual(useStudioStore.getState().manuscript.annotations, manuscript.annotations);
    assert.equal(useStudioStore.getState().manuscript.sections[3]!.blocks[0]!.id, 'child-body');
    assert.ok(useStudioStore.getState().pendingChangeSet);
  } finally { useStudioStore.setState(original); }
});
