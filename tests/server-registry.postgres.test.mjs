import assert from 'node:assert/strict';
import test from 'node:test';
import { readFile } from 'node:fs/promises';
import pg from '../server/node_modules/pg/lib/index.js';
const url=process.env.OMI_TEST_POSTGRES_URL;
if(!url) throw Error('OMI_TEST_POSTGRES_URL is required');
const schema='registry_'+crypto.randomUUID().replaceAll('-','');
const admin=new pg.Client({connectionString:url}); await admin.connect(); await admin.query(`CREATE SCHEMA ${schema}`);
const scoped=new URL(url); scoped.searchParams.set('options',`-csearch_path=${schema}`);
process.env.DATABASE_URL=scoped.href;
const sql=new pg.Client({connectionString:scoped.href}); await sql.connect();
let prisma;
test('real registry migrations and concurrent proof/token CAS',async t=>{
 t.after(async()=>{await prisma?.$disconnect(); await sql.end(); await admin.query(`DROP SCHEMA ${schema} CASCADE`); await admin.end();});
 await sql.query(await readFile(new URL('../server/prisma/migrations/20261021180000_add_studio_server_directory/migration.sql',import.meta.url),'utf8'));
 await sql.query(`INSERT INTO studio_server_directory_entries(id,name,origin,hostname,domain_challenge_hash,heartbeat_token_hash,updated_at) VALUES('legacy','Synthetic','https://legacy.example.org','legacy.example.org',repeat('a',64),repeat('b',64),now())`);
 await sql.query(await readFile(new URL('../server/prisma/migrations/20261022080000_registry_registration_authority/migration.sql',import.meta.url),'utf8'));
 assert.equal((await sql.query("SELECT status FROM studio_server_directory_entries WHERE id='legacy'")).rows[0].status,'REVOKED');
 const {PrismaClient}=await import('../server/dist/generated/prisma/client.js'); const {PrismaPg}=await import('../server/node_modules/@prisma/adapter-pg/dist/index.js');
 prisma=new PrismaClient({adapter:new PrismaPg({connectionString:scoped.href},{schema})}); globalThis.prisma=prisma;
 const {serverRegistryRepository:r}=await import('../server/dist/repositories/serverRegistryRepository.js');
 const data={name:'Synthetic',origin:'https://synthetic.example.org',hostname:'synthetic.example.org',domainChallengeHash:'d'.repeat(64),registrationTokenHash:'p'.repeat(64),heartbeatTokenHash:'t'.repeat(64),challengeExpiresAt:new Date(Date.now()+60000),capabilities:[]};
 assert.equal(await r.register('test',data,false),true);
 assert.equal(await r.claim('test','wrong'),false);
 const claims=await Promise.all([r.claim('test',data.registrationTokenHash),r.claim('test',data.registrationTokenHash)]); assert.equal(claims.filter(Boolean).length,1);
 assert.equal(await r.activate('test',data.registrationTokenHash,'n'.repeat(64),'https://github.com/example/catalog/issues/1'),true);
 assert.equal(await r.claim('test',data.registrationTokenHash),false);
 const rotations=await Promise.all([r.rotate('test','n'.repeat(64),'a'.repeat(64)),r.rotate('test','n'.repeat(64),'b'.repeat(64))]); assert.equal(rotations.filter(Boolean).length,1);
 const entry=await r.findById('test'); assert.equal(entry.registrationTokenHash,null);
 assert.equal(await r.revoke('test',entry.heartbeatTokenHash,'x'.repeat(64)),true);
 assert.equal(await r.heartbeat('test',entry.heartbeatTokenHash),false);
 assert.equal(await r.rotate('test',entry.heartbeatTokenHash,'y'.repeat(64)),false);
 assert.deepEqual(await r.list(),[]);
 await r.register('expired',{...data,origin:'https://expired.example.org',challengeExpiresAt:new Date(0)},false);
 assert.equal(await r.claim('expired',data.registrationTokenHash),false);
});
